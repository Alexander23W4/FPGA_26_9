/******************************************************************************
* app/app.h —— 应用层：初始化 + 命令分发
*
*   分层的意图：main.c 只管"启动"，不掺任何业务逻辑。
*   要加一个新功能，就在 feat/ 下加一对 .c/.h，
*   然后往 app/app.c 的命令表里加一行 —— 不用动 main.c。
******************************************************************************/

#ifndef APP_APP_H
#define APP_APP_H

/* 集中初始化：eMMC / VDMA 的状态探测。返回 0 = eMMC 可用 */
int  app_init(void);

/* 打印可用命令 */
void app_help(void);

/* 主循环：从串口收一个命令字节，分发给对应 feature。永不返回 */
void app_run(void);

#endif /* APP_APP_H */
