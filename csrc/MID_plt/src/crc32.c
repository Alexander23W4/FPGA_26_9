/******************************************************************************
* common/crc32.c —— CRC32 实现（按位算，不查表）
*
*   128KB 的图按位算大约 100 万次循环，在 667MHz 的 A9 上是毫秒级，
*   完全不需要为了省这点时间引入 1KB 的表。
******************************************************************************/

#include "common/crc32.h"

u32 crc32_calc(const u8 *p, u32 n)
{
    u32 crc = 0xFFFFFFFFu;
    u32 i;
    u32 b;

    for (i = 0u; i < n; i++) {
        crc ^= (u32)p[i];
        for (b = 0u; b < 8u; b++) {
            /* 最低位为 1 就异或多项式，否则只右移 */
            crc = (crc >> 1) ^ (0xEDB88320u & (u32)(-(s32)(crc & 1u)));
        }
    }
    return crc ^ 0xFFFFFFFFu;
}
